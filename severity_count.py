import argparse
import re
import unicodedata
from collections import Counter, defaultdict

import pandas as pd


def normalize_text(text: str) -> str:
	"""Lowercase and remove accents to make French spelling variants comparable."""
	text = str(text).lower()
	text = unicodedata.normalize("NFKD", text)
	return "".join(ch for ch in text if not unicodedata.combining(ch))


def build_patterns() -> dict[str, str]:
	"""Regex patterns for pain-description terms in normalized text."""
	return {
		"douleur": r"\bdouleur(?:s)?\b",
		"aigu(e/s)": r"\baigu(?:e|es|s)?\b",
		"intense": r"\bintense(?:s)?\b",
		"severe": r"\bsevere(?:s)?\b",
		"importante": r"\bimportant(?:e|es|s)?\b",
		"vive": r"\bvive(?:s)?\b",
		"localisee": r"\blocalis(?:e|ee|ees|es)\b",
	}


def main() -> None:
	parser = argparse.ArgumentParser(
		description="Count pain-related terms in justification_courte by group."
	)
	parser.add_argument(
		"--csv",
		default="poc_results.csv",
		help="Path to CSV file generated by poc.py (default: poc_results.csv)",
	)
	args = parser.parse_args()

	df = pd.read_csv(args.csv)

	required_cols = {"justification_courte", "group"}
	missing = required_cols - set(df.columns)
	if missing:
		raise ValueError(f"Missing required columns: {', '.join(sorted(missing))}")

	patterns = build_patterns()
	counts_by_group: dict[str, Counter] = defaultdict(Counter)
	docs_with_term_by_group: dict[str, Counter] = defaultdict(Counter)

	for _, row in df.iterrows():
		group = str(row["group"]).strip()
		text = normalize_text(row["justification_courte"])
		row_has_term = {}

		for term, pattern in patterns.items():
			matches = re.findall(pattern, text)
			counts_by_group[group][term] += len(matches)
			row_has_term[term] = len(matches) > 0

		for term, present in row_has_term.items():
			if present:
				docs_with_term_by_group[group][term] += 1

	groups = sorted(counts_by_group.keys())
	for group in groups:
		print(f"\n=== Group: {group} ===")
		total_rows = int((df["group"].astype(str).str.strip() == group).sum())
		print(f"Rows in group: {total_rows}")
		print("Term | Total occurrences | Rows containing term")
		print("-" * 52)
		for term, _ in counts_by_group[group].most_common():
			occ = counts_by_group[group][term]
			rows = docs_with_term_by_group[group][term]
			print(f"{term:<12} {occ:>8} {rows:>22}")


if __name__ == "__main__":
	main()
